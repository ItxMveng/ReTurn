import 'dart:ui' show PlatformDispatcher;

/// Pays (ISO 3166-1 alpha-2) avec indicatif téléphonique et noms FR/EN.
class Country {
  final String code;
  final String dial;
  final String nameFr;
  final String nameEn;

  const Country(this.code, this.dial, this.nameFr, this.nameEn);

  String name(String languageCode) => languageCode == 'fr' ? nameFr : nameEn;

  /// Drapeau emoji (indicateurs régionaux Unicode).
  String get flag => String.fromCharCodes(
        code.codeUnits.map((c) => 0x1F1E6 + c - 0x41),
      );
}

Country? countryByCode(String? code) {
  if (code == null) return null;
  final upper = code.toUpperCase();
  for (final c in kCountries) {
    if (c.code == upper) return c;
  }
  return null;
}

/// Pays déduit de la langue/région de l'appareil (ex. fr_CM → CM), sinon null.
String? deviceCountryCode() {
  for (final locale in PlatformDispatcher.instance.locales) {
    final code = locale.countryCode;
    if (code != null && countryByCode(code) != null) return code.toUpperCase();
  }
  return null;
}

/// Convertit un numéro saisi en format international (E.164) en s'appuyant sur
/// l'indicatif du pays. Un numéro déjà en « +… » ou « 00… » est conservé.
String toInternationalPhone(String input, {String? countryCode}) {
  final p = input.trim().replaceAll(RegExp(r'[\s\-.()]'), '');
  if (p.startsWith('+')) return p;
  if (p.startsWith('00')) return '+${p.substring(2)}';
  final dial = countryByCode(countryCode)?.dial;
  if (dial == null) return '+$p';
  // Numéro saisi avec l'indicatif mais sans « + » (ex. 33612345678).
  if (p.startsWith(dial) && p.length >= dial.length + 8) return '+$p';
  // Zéro de tronc national (ex. 06… en France) : retiré derrière l'indicatif.
  final national = p.startsWith('0') ? p.substring(1) : p;
  return '+$dial$national';
}

